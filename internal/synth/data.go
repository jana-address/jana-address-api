// City is a settlement with the ways people write it.
type City struct {
	Name     string // canonical Russian name
	Province string // canonical province; equals Name for Алматы, Астана, Шымкент
	Weight   float64
	Kaz      string   // Kazakh spelling when it differs from Name
	Latin    []string // first is the usual one; "~" marks an old name
	Old      []string // old or colloquial Cyrillic names
	Post     string   // first four digits of the postcode
	Village  bool
	MkrShare float64 // share of addresses written by microdistrict; 0 means default

	Streets   []Street
	Mkr       []Name
	ZhK       []string
	Districts []District
}

// Street is a named street of a known type.
type Street struct {
	Type string // canonical street_type
	Name
}

// Name is a Russian spelling with an optional Kazakh one.
type Name struct{ Ru, Kz string }

// District is a city or rural district: canonical Russian and the Kazakh base.
type District struct{ Name, Kz string }

func (c *City) big() bool { return c.Province == c.Name }

var streetCodes = map[byte]string{'u': "улица", 'p': "проспект", 'l': "переулок", 'b': "бульвар", 's': "шоссе"}

// streets parses "u Абая|Абай": type code, Russian name, optional Kazakh name.
func streets(spec ...string) []Street {
	out := make([]Street, 0, len(spec))
	for _, s := range spec {
		out = append(out, Street{Type: streetCodes[s[0]], Name: name(s[2:])})
	}
	return out
}

func name(s string) Name {
	ru, kz, _ := strings.Cut(s, "|")
	return Name{ru, kz}
}

func names(groups ...[]string) []Name {
	var out []Name
	for _, g := range groups {
		for _, s := range g {
			out = append(out, name(s))
		}
	}
	return out
}

func list(s ...string) []string { return s }

// series yields "Аксай-1|Ақсай-1" .. "Аксай-n|Ақсай-n".
func series(ru, kz string, from, to int) []string {
	var out []string
	for i := from; i <= to; i++ {
		n := strconv.Itoa(i)
		s := ru + "-" + n
		if kz != "" {
			s += "|" + kz + "-" + n
		}
		out = append(out, s)
	}
	return out
}

func nums(xs ...int) []string {
	var out []string
	for _, x := range xs {
		out = append(out, strconv.Itoa(x))
	}
	return out
}

func numRange(from, to int) []string {
	var out []string
	for i := from; i <= to; i++ {
		out = append(out, strconv.Itoa(i))
	}
	return out
}

