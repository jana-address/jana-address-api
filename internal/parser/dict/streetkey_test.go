package dict

import "testing"

func TestStreetKey(t *testing.T) {
	for in, want := range map[string][2]string{
		"улица Абая":            {"абая", "улица"},
		"Абай даңғылы":          {"абай", "проспект"},
		"микрорайон Аксай-3А":   {"аксай 3а", "микрорайон"},
		"Аксай 3а":              {"аксай 3а", ""},
		"Д. Кунаева":            {"кунаева", ""},
		"Рыбинский переулок":    {"рыбинский", "переулок"},
		"Жетісу-3 шағын ауданы": {"жетису 3", "микрорайон"},
		"Төле би көшесі":        {"толе би", "улица"},
		"8-й микрорайон":        {"8", "микрорайон"},
		"Жибек Жолы":            {"жибек жолы", ""},
		"Коргалжын тас жолы":    {"коргалжын", "шоссе"},
		"ЖК Алатау Гранд":       {"алатау гранд", "жилой комплекс"},
		"проезд Майлина":        {"майлина", ""},
		"Ш. Уалиханова":         {"уалиханова", ""},
		"улица":                 {"улица", ""},
	} {
		k, typ := StreetKey(in)
		if k != want[0] || typ != want[1] {
			t.Errorf("StreetKey(%q) = %q, %q, want %q, %q", in, k, typ, want[0], want[1])
		}
	}
	if HouseKey("12 А") != "12а" || HouseKey("55/6") != "55/6" {
		t.Error("HouseKey")
	}
}
